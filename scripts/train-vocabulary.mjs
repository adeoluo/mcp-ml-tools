// Regenerates src/tools/bpe-merges.ts from the training corpus. Run `npm run build` first.
import { writeFileSync } from "node:fs";
import { trainBpe } from "../dist/tools/bpe.js";
import { BPE_TRAINING_CORPUS } from "../dist/tools/bpe-corpus.js";
import { MERGE_COUNT } from "../dist/tools/bpe-settings.js";

const merges = trainBpe(BPE_TRAINING_CORPUS, MERGE_COUNT);
const lines = [];
for (let i = 0; i < merges.length; i += 8) {
  lines.push(
    "  " +
      merges
        .slice(i, i + 8)
        .map(([left, right]) => `[${left}, ${right}]`)
        .join(", ") +
      ",",
  );
}
const source = `// Generated by scripts/train-vocabulary.mjs. Do not edit by hand.
import type { Merge } from "./bpe.js";

export const BPE_MERGES: readonly Merge[] = [
${lines.join("\n")}
];
`;
writeFileSync(new URL("../src/tools/bpe-merges.ts", import.meta.url), source);
console.log(`wrote ${merges.length} merges (vocabulary size ${256 + merges.length})`);
